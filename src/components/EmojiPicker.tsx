interface EmojiPickerProps {
  onSelect: (emoji: string) => void;
  onClose: () => void;
}

export function EmojiPicker({ onSelect, onClose }: EmojiPickerProps) {
  const [cat, setCat] = useState(0);

  return (
    <AnimatePresence>
      <motion.div
        initial={{ opacity: 0, y: 8, scale: 0.97 }}
        animate={{ opacity: 1, y: 0, scale: 1 }}
        exit={{ opacity: 0, y: 8, scale: 0.97 }}
        transition={{ duration: 0.12 }}
        className="absolute bottom-14 left-0 z-50 rounded-2xl shadow-xl overflow-hidden"
        style={{ width: 320, background: 'var(--surface-card)', border: '1px solid var(--border)' }}
        onMouseLeave={onClose}
      >
        {/* Category tabs */}
        <div className="flex overflow-x-auto gap-0 border-b" style={{ borderColor: 'var(--border)', scrollbarWidth: 'none' }}>
          {CATEGORIES.map((c, i) => (
            <button key={i} onClick={() => setCat(i)}
              className="px-3 py-2.5 text-base flex-shrink-0 transition-all"
              style={{
                background: cat === i ? 'var(--surface-muted)' : 'transparent',
                border: 'none', cursor: 'pointer',
                borderBottom: cat === i ? '2px solid var(--gold)' : '2px solid transparent',
              }}>
              {c.emojis[0]}
            </button>
          ))}
        </div>

        {/* Emoji grid */}
        <div className="p-2 overflow-y-auto" style={{ maxHeight: 220 }}>
          <div style={{ display: 'grid', gridTemplateColumns: 'repeat(8, 1fr)', gap: 2 }}>
            {CATEGORIES[cat].emojis.map((e) => (
              <button key={e} onClick={() => onSelect(e)}
                className="flex items-center justify-center rounded-lg transition-all text-xl hover:scale-110"
                style={{ width: 34, height: 34, background: 'transparent', border: 'none', cursor: 'pointer', fontSize: 20 }}>
                {e}
              </button>
            ))}
          </div>
        </div>
      </motion.div>
    </AnimatePresence>
  );
}
